import { chromium } from "playwright-core";
const b = await chromium.launch({ executablePath: "/home/ubuntu/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome", headless: true, args: ["--no-sandbox"] });
const c = await b.newContext({ viewport: { width: 1440, height: 1000 }, ignoreHTTPSErrors: true });
const p = await c.newPage();
const errs = []; p.on("pageerror", e => errs.push(e.message));
const email = "qa-map-" + Date.now() + "@example.invalid";
await p.goto("https://127.0.0.1:5175/", { waitUntil: "domcontentloaded" });
await p.waitForTimeout(2000);
await p.getByRole("button", { name: "登录 / 注册", exact: true }).click();
await p.getByRole("button", { name: "没有账号？注册一个" }).click();
await p.getByLabel("邮箱", { exact: true }).fill(email);
await p.getByLabel(/密码（10—128位/).fill("Qa-Map-Test-123");
await p.getByRole("button", { name: "创建账号", exact: true }).click();
await p.getByRole("button", { name: "退出登录" }).waitFor({ timeout: 20000 });
await p.waitForTimeout(900);
const ex = p.getByRole("button", { name: "退出新手教程" });
if (await ex.count()) await ex.click();
await p.locator(".orbit-trigger").click();
await p.locator(".nav-map").waitFor({ timeout: 8000 });
await p.locator('[data-page="map"]').click();
await p.waitForTimeout(7000);
console.log("地图 canvas 数:", await p.locator("canvas").count());
console.log("平台图钉:", await p.locator(".amap-marker, .map-pin, [class*=pin]").count());
await p.screenshot({ path: "/home/ubuntu/workspaces/competition/app-redesign/artifacts/rd-map-nolabels.png" });
console.log("errors:", errs.slice(0, 3));
await b.close();
