import { chromium } from "playwright-core";
const base="http://127.0.0.1:5173";
const b=await chromium.launch({executablePath:"/home/ubuntu/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome",headless:true,args:["--no-sandbox"]});
const c=await b.newContext({viewport:{width:1500,height:1100}});
await c.request.post(base+"/api/auth/register",{data:{email:"mg-"+Date.now()+"@example.invalid",password:"Map-Test-12345!"}});
const ses=await (await c.request.get(base+"/api/auth/session")).json();
const csrf=ses.csrf||ses.session?.csrf;
const jobs=await (await c.request.get(base+"/api/jobs?limit=6")).json();
const list=(jobs.jobs||jobs.items||[]).slice(0,3);
for(const j of list) await c.request.put(base+"/api/job-intents/"+j.id,{headers:{"X-CSRF-Token":csrf}});
const p=await c.newPage();
const errs=[]; p.on("pageerror",e=>errs.push(e.message.slice(0,120)));
await p.goto(base+"/#map");
await p.locator(".map-pin").first().waitFor({timeout:20000});
await p.waitForTimeout(2500);
const boxes=p.getByRole("checkbox");
await boxes.nth(2).check(); await boxes.nth(3).check();
await p.waitForTimeout(3500);
console.log("pins by kind:", JSON.stringify(await p.evaluate(()=>{
  const out={}; for(const el of document.querySelectorAll(".map-pin")){const k=el.dataset.kind; out[k]=(out[k]||0)+1;} return out;
})));
const hotel=p.locator('.map-pin[data-kind="hotel"]').first();
await hotel.click({force:true});
await p.waitForTimeout(500);
console.log("酒店弹窗:", (await p.locator(".map-popup").innerText()).replace(/\n/g," | ").slice(0,150));
await p.getByRole("button",{name:"以中心点为起点"}).click();
await p.locator('.map-pin[data-kind="job"]').first().click({force:true});
await p.waitForTimeout(400);
await p.getByRole("button",{name:"以中心点为终点"}).click();
await p.getByRole("button",{name:"规划路线"}).click();
await p.waitForTimeout(4000);
console.log("error:", await p.locator(".error").count()? await p.locator(".error").first().innerText():"none");
console.log("路线:", await p.locator(".map-route-summary").count()? await p.locator(".map-route-summary").innerText():"无");
console.log("polyline:", await p.locator(".map-svg polyline").count());
await p.getByRole("button",{name:/帮我在附近做选择/}).click();
await p.locator(".map-ai").waitFor({timeout:180000});
console.log("AI:", (await p.locator(".map-ai-advice").innerText()).slice(0,70), "| picks:", await p.locator(".map-ai-pick").count());
await p.screenshot({path:"/tmp/map-full.png"});
console.log("errors:", errs.slice(0,3));
await b.close();
