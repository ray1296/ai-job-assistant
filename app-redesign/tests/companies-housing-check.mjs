import { chromium } from "playwright-core";
const base="http://127.0.0.1:5173";
const b=await chromium.launch({executablePath:"/home/ubuntu/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome",headless:true,args:["--no-sandbox"]});
const c=await b.newContext({viewport:{width:1400,height:900}});
await c.request.post(base+"/api/auth/register",{data:{email:"co-"+Date.now()+"@example.invalid",password:"Co-Test-12345!"}});
const p=await c.newPage();
await p.goto(base+"/#companies");
await p.locator(".company-card").first().waitFor({timeout:20000});
console.log("企业卡片:", await p.locator(".company-card").count());
await p.locator(".company-card").first().click();
await p.locator(".company-detail").waitFor({timeout:10000});
console.log("详情标题:", await p.locator(".company-detail h2").innerText());
console.log("iframe 数（应为0）:", await p.locator("iframe").count());
await p.screenshot({path:"/tmp/companies.png", fullPage:true});
