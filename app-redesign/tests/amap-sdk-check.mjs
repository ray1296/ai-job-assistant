import { chromium } from "playwright-core";
const base="http://127.0.0.1:5173";
const b=await chromium.launch({executablePath:"/home/ubuntu/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome",headless:true,args:["--no-sandbox"]});
const c=await b.newContext({viewport:{width:1500,height:1000}});
await c.request.post(base+"/api/auth/register",{data:{email:"js-"+Date.now()+"@example.invalid",password:"Js-Test-12345!"}});
const ses=await (await c.request.get(base+"/api/auth/session")).json();
const csrf=ses.csrf||ses.session?.csrf;
const jobs=await (await c.request.get(base+"/api/jobs?limit=6")).json();
for(const j of (jobs.jobs||jobs.items||[]).slice(0,2)) await c.request.put(base+"/api/job-intents/"+j.id,{headers:{"X-CSRF-Token":csrf}});
const p=await c.newPage();
const errs=[]; p.on("pageerror",e=>errs.push(e.message.slice(0,140)));
p.on("console",m=>{ if(m.type()==="error") errs.push("C:"+m.text().slice(0,120)); });
await p.goto(base+"/#map");
await p.locator(".map-full").waitFor({timeout:20000});
await p.waitForTimeout(9000);
console.log("AMap:", await p.evaluate(()=>typeof window.AMap));
console.log("容器:", await p.locator(".amap-host canvas").count(), "canvas");
console.log("高德控件:", await p.locator(".amap-control, .amap-toolbar, .amap-scalecontrol, .amap-maptypecontrol").count());
console.log("标记:", await p.locator(".amap-dot").count());
await p.screenshot({path:"/tmp/map-amap.png"});
console.log("errors:", errs.slice(0,6));
await b.close();
