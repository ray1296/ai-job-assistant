import { chromium } from "playwright-core";
const b=await chromium.launch({executablePath:"/home/ubuntu/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome",headless:true,args:["--no-sandbox"]});
const c=await b.newContext({viewport:{width:1440,height:1100}});
const p=await c.newPage();
const errs=[]; p.on("pageerror",e=>errs.push(e.message));
await p.goto("http://127.0.0.1:5173/");
await p.getByRole("button",{name:"旅程地图",exact:true}).click();
await p.getByRole("heading",{name:"你的旅程地图"}).waitFor();
await p.getByRole("button",{name:"收起星盘 ×"}).click();
await p.getByRole("button",{name:"登录 / 注册",exact:true}).click();
await p.getByRole("button",{name:"没有账号？注册一个"}).click();
await p.getByLabel("邮箱",{exact:true}).fill("dash-"+Date.now()+"@example.invalid");
await p.getByLabel("密码（10—128位）").fill("Dash-Test-123!");
await p.getByRole("button",{name:"创建账号",exact:true}).click();
await p.getByRole("button",{name:"退出登录"}).waitFor();
await p.goto("http://127.0.0.1:5173/#dashboard");
await p.locator(".dash-dark-kpi").first().waitFor({timeout:25000});
await p.waitForTimeout(1500);
console.log("KPI:", (await p.locator(".dash-dark-kpis").innerText()).replace(/\n/g," | "));
console.log("canvas:", await p.locator(".dash-dark-chart canvas").count(), "rows:", await p.locator(".dash-dark-row").count(), "tabs:", await p.locator(".city-choice").count());
await p.screenshot({path:"/tmp/dash.png", fullPage:true});
await p.getByRole("button",{name:"上海",exact:true}).first().click();
await p.waitForTimeout(1500);
console.log("上海 rows:", await p.locator(".dash-dark-row").count());
console.log("errors:", errs.slice(0,3));
await b.close();
